"""Generator for install-script-hashes.MANIFEST (finding: served scripts carry no fingerprint, #763).

Owner words O970 (*"we need to fix the install scripts"* — the scripts are part of the release
process) and O971 (*"yes, we can put the sidecars in the git repo and on the website if needed"*).
This is the REPO half of O971: a manifest whose hashes are of the COMMITTED bytes, so a script
change and its fingerprint move in the same diff.

Why a manifest and not per-file `.sha256` sidecars committed beside each script: the build rewrites
the served installers before publishing them — the #360 block seds the real `venya-common.sh` hash
into each installer's `__VENYA_COMMON_SHA256__` placeholder, and the local-serve pass rewrites
`TARBALL_URL` — so served bytes are NOT repo bytes by construction, and a committed per-script
sidecar could not describe the bytes a customer can actually check. The SERVED half is emitted by
the build itself (installer repo, `create-tarball-and-serve.sh`), after every substitution; this
file is the repo half, and the two mean different things on purpose.

Line format: ``<sha256>  <path>  <role>`` — the ``hash`` and ``path`` use the two-space idiom
`sha256sum` prints, but the third field means this file is NOT `sha256sum -c` consumable and does not
claim to be: it is a repo-freshness artifact, read by its own generator. The SERVED sidecars the build
emits ARE `sha256sum -c` consumable (plain two-field lines).

Usage:
    gen_install_script_hashes.py --write    # rewrite the manifest from the working tree
    gen_install_script_hashes.py --check    # exit 1 on drift, printing the reason; exit 0 in sync

The currency half lives in packages/server/tests/test_install_script_hashes_763.py.
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess  # nosec B404 — own git reads, fixed argv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
MANIFEST = REPO_ROOT / "install-script-hashes.MANIFEST"

#: Tracked-script discovery is by git, not by a hand list: a script ADDED to the repo must join
#: the manifest, and the test fails until it is (that is the currency claim made falsifiable).
SCRIPT_GLOBS = ("*.sh", "*.ps1")

#: Roles are the human classification; an unknown script still gets fingerprinted (refusing to
#: generate on an unclassified name would let a new script escape coverage silently).
ROLES: dict[str, str] = {
    "install-venya-core.sh": "served installer, root-run",
    "install-venya-executor.sh": "served installer, root-run",
    "install-venya-cli.sh": "served installer, workstation",
    "uninstall-venya-core.sh": "served uninstaller, root-run",
    "uninstall-venya-executor.sh": "served uninstaller, root-run",
    "uninstall-venya-cli.sh": "served uninstaller, workstation",
    "venya-common.sh": "shared library, fetched by installers",
    "install-venya-cli.ps1": "served Windows installer, conditional by ref",
    "uninstall-venya-cli.ps1": "served Windows uninstaller, conditional by ref",
    "scripts/deploy-record.sh": "repo build helper, not served",
    "scripts/pin-requirements.sh": "repo build helper, not served",
}
DEFAULT_ROLE = "tracked script, unclassified"


def tracked_scripts(root: Path = REPO_ROOT) -> list[str]:
    out = subprocess.run(  # nosec B603 B607 — fixed argv, git on PATH, own repo
        ["git", "-C", str(root), "ls-files", *SCRIPT_GLOBS],
        capture_output=True,
        text=True,
        check=True,
    )
    return sorted(p for p in out.stdout.splitlines() if p)


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_manifest(root: Path = REPO_ROOT) -> str:
    lines = [
        "# install-script-hashes.MANIFEST — fingerprints of the COMMITTED script bytes (repo half of O971).",
        "# Generated by packages/server/scripts/gen_install_script_hashes.py --write; drift is a RED test",
        "# (packages/server/tests/test_install_script_hashes_763.py). The SERVED bytes differ from these by",
        "# design: the build embeds the shared-library hash and rewrites the download base, and it emits the",
        "# served .sha256 sidecars AFTER those substitutions. Do not hand-edit this file.",
    ]
    for rel in tracked_scripts(root):
        digest = sha256_of(root / rel)
        role = ROLES.get(rel, DEFAULT_ROLE)
        lines.append(f"{digest}  {rel}  {role}")
    return "\n".join(lines) + "\n"


def parse_manifest(text: str) -> dict[str, tuple[str, str]]:
    """path -> (hash, role). Comments and blank lines are skipped."""
    entries: dict[str, tuple[str, str]] = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        digest, rest = line.split("  ", 1)
        path, _, role = rest.partition("  ")
        entries[path] = (digest, role)
    return entries


def check(root: Path = REPO_ROOT) -> list[str]:
    """The drift report — empty means in sync. Rehashes the working-tree bytes, so an uncommitted
    script edit with a stale manifest fails HERE, before any commit can publish it. The manifest
    read is under `root` too, so a test can point the whole check at a fixture tree."""
    manifest = root / MANIFEST.name
    if not manifest.exists():
        return [f"missing manifest: {manifest.name} (run --write)"]
    entries = parse_manifest(manifest.read_text(encoding="utf-8"))
    problems: list[str] = []
    found = tracked_scripts(root)
    for rel in found:
        want = sha256_of(root / rel)
        if rel not in entries:
            problems.append(f"no manifest row for tracked script: {rel}")
        elif entries[rel][0] != want:
            problems.append(f"drift: {rel} manifest says {entries[rel][0][:12]}…, bytes are {want[:12]}…")
    for rel in entries:
        if rel not in found:
            problems.append(f"manifest row for a path git no longer tracks: {rel}")
    return problems


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the manifest from the working tree")
    mode.add_argument("--check", action="store_true", help="exit 1 on drift (reads only)")
    args = ap.parse_args(argv)
    if args.write:
        MANIFEST.write_text(build_manifest(), encoding="utf-8")
        print(f"wrote {MANIFEST}")
        return 0
    problems = check()
    if problems:
        for p in problems:
            print(f"DRIFT: {p}")
        return 1
    n = len(tracked_scripts())
    print(f"in sync: {n} tracked scripts rehashed, {n} manifest rows")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
